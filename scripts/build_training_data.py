"""Build the website curves from the supplied 2026-11-12 report tables."""
import argparse
import csv
import json
import math
from pathlib import Path
from statistics import fmean


def read_table(path):
    with path.open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def number(value):
    result = float(value)
    if not math.isfinite(result):
        raise ValueError('Non-finite source observation')
    return result


def build(source):
    data = {}
    for model in ['supermimic', 'morphmimic']:
        tables = source / model / 'tables'
        logs = read_table(tables / '全部训练曲线数据.csv')
        robots = ['g1'] if model == 'supermimic' else ['h2', 'g1']
        fields = {
            'series': ('train/episode_norm_return' if model == 'supermimic' else 'collect/mean_norm_return', 1),
            'loss': ('wm/state_loss', 1),
        }
        fields.update({'prediction': ('wm/online_nse_8step', 1)} if model == 'supermimic' else {
            'pelvis': ('wm/err8_pelvis_m', 100),
            'joint': ('wm/err8_joint_rad', 180 / math.pi),
        })
        data[model] = {key: {} for key in fields}
        data[model]['validation'] = {}
        for key, (field, multiplier) in fields.items():
            for robot in robots:
                points, window = [], []
                for row in logs:
                    if model == 'morphmimic' and row['robot'] != robot:
                        continue
                    step, value = int(row['iteration']), number(row[field]) * multiplier
                    if key in ('loss', 'prediction') and value <= 0:
                        raise ValueError(f'Non-positive logarithmic observation: {model}/{field}/{step}')
                    if points and step <= points[-1][0]:
                        raise ValueError(f'Unordered or duplicate step: {model}/{robot}/{step}')
                    # These are the two recorded restart boundaries in this joint run.
                    if model == 'morphmimic' and step in (10050, 20050):
                        window = []
                    window.append(value)
                    window = window[-(20 if model == 'supermimic' else 21):]
                    points.append([step, value, fmean(window)])
                data[model][key][robot] = points
        if model == 'supermimic':
            evaluations = read_table(tables / '历次验证.csv')
            data[model]['validation']['g1'] = [[int(row['迭代']), number(row['整段平均归一化回报']), number(row['完成率'])] for row in evaluations]
        else:
            evaluations = read_table(tables / '历次评测.csv')
            for robot in robots:
                data[model]['validation'][robot] = [[int(row['iteration']), number(row['norm_return']), number(row['completion'])] for row in evaluations if row['robot'] == robot and row['split'] == 'development' and row['repeat'] == 'primary']
    return data


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True, help='Directory containing supermimic/ and morphmimic/ report tables')
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / 'assets/data/training-curves.js'
    output.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(build(args.source), ensure_ascii=False, separators=(',', ':'), allow_nan=False)
    output.write_text('// Generated by scripts/build_training_data.py. See docs/TRAINING_DATA.md.\nconst trainingCurves = ' + payload + ';\n')
    print(f'Built {output.name}: {output.stat().st_size:,} bytes')
